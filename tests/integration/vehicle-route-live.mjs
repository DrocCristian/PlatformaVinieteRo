import {chromium} from '@playwright/test';
import fs from 'node:fs';import assert from 'node:assert/strict';
const fixture=JSON.parse(fs.readFileSync('work/route-auth-fixture.json','utf8'));
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1280,height:900}});
page.setDefaultTimeout(30000);
const base='http://127.0.0.1:3000';
try{
 await page.goto(base+'/autentificare');
 await page.getByLabel('E-mail',{exact:true}).fill(fixture.email);
 await page.getByLabel('Parolă',{exact:true}).fill(fixture.password);
 await page.getByRole('button',{name:'Intră în cont',exact:true}).click();
 await page.waitForURL('**/cont');
 const form=page.locator('section').filter({has:page.getByRole('heading',{name:'Adaugă un vehicul',exact:true})});
 await form.getByLabel('Număr de înmatriculare',{exact:true}).fill('B 123 TST');
 await form.getByLabel('Denumire (opțional)').fill('Camion test temporar');
 await form.getByLabel('Tip vehicul',{exact:true}).selectOption('goods');
 await form.getByLabel('Categoria J',{exact:true}).selectOption('N2');
 await form.getByLabel('Masa F.1 (kg)',{exact:true}).fill('7500');
 await form.getByLabel('Masa F.2 (kg)',{exact:true}).fill('7500');
 await form.getByLabel('Locuri S.1 (cu șofer)',{exact:true}).fill('3');
 await form.getByLabel('Cu remorcă / rulotă / semiremorcă',{exact:true}).check();
 await form.getByLabel('Numărul remorcii',{exact:true}).fill('B123REM');
 await form.getByLabel('Categoria remorcii',{exact:true}).selectOption('O2');
 await form.getByLabel('Remorcă F.1 (kg)',{exact:true}).fill('1500');
 await form.getByLabel('Remorcă F.2 (kg)',{exact:true}).fill('1500');
 await form.getByRole('button',{name:'Salvează vehiculul',exact:true}).click();
 await form.getByRole('status').waitFor();
 await page.reload();
 await page.getByRole('link',{name:'Planifică o cursă',exact:true}).click();
 await page.getByLabel('De unde pleci?',{exact:true}).fill('Cluj-Napoca, România');
 await page.getByLabel('Unde ajungi?',{exact:true}).fill('Viena, Austria');
 await page.getByLabel('Plecare',{exact:true}).fill('2099-01-01');
 await page.getByLabel('Ultima zi a călătoriei',{exact:true}).fill('2099-01-03');
 await page.getByRole('button',{name:'Salvează cursa',exact:true}).click();
 await page.getByRole('status').waitFor();await page.reload();
 await page.getByRole('heading',{name:'Cluj-Napoca, România → Viena, Austria',exact:true}).waitFor();
 let response=await page.request.get(base+'/cont/date/export');assert.equal(response.status(),200);
 let data=await response.json();
 assert.equal(data.vehicles.length,1);assert.equal(data.vehicles[0].technical.f1,7500);
 assert.equal(data.vehicles[0].technical.trailer.plate,'B123REM');
 assert.equal(data.journeys.length,1);assert.equal(data.journeys[0].route_request.origin,'Cluj-Napoca, România');
 assert.equal(data.journeys[0].vehicle_snapshot.technical.f1,7500);
 await page.goto(base+'/cont');
 const saved=page.locator('.saved-vehicle').first();
 await saved.getByText('Editează datele',{exact:true}).click();
 await saved.getByLabel('Masa F.1 (kg)',{exact:true}).fill('8000');
 await saved.getByRole('button',{name:'Salvează vehiculul',exact:true}).click();
 await saved.getByRole('status').waitFor();
 response=await page.request.get(base+'/cont/date/export');data=await response.json();
 assert.equal(data.vehicles[0].technical.f1,8000);
 assert.equal(data.journeys[0].vehicle_snapshot.technical.f1,7500);
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+'/cont/calatorii');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'work/route-account-mobile.png',fullPage:true});
 await page.goto(base+'/cont');
 await page.getByRole('button',{name:'Arhivează B123TST',exact:true}).click();
 await page.goto(base+'/cont/calatorii');
 await page.getByText('Adaugă mai întâi vehiculul în',{exact:false}).waitFor();
 console.log('PASS saved truck/trailer, route from saved vehicle, owner export, immutable journey snapshot, mobile layout, archived vehicle unavailable');
}finally{await browser.close();}
